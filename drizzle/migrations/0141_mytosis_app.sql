CREATE TABLE public.mytosis_members (
  user_id uuid PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'viewer' CHECK (role IN ('admin','editor','viewer')),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.mytosis_role(_user_id uuid)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT CASE
    WHEN public.is_erp_admin(_user_id) THEN 'admin'
    ELSE (SELECT role FROM public.mytosis_members WHERE user_id = _user_id)
  END
$$;

CREATE OR REPLACE FUNCTION public.mytosis_can_edit(_user_id uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT coalesce(public.mytosis_role(_user_id) IN ('admin','editor'), false)
$$;

CREATE TABLE public.mytosis_settings (
  id integer PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  box_width integer NOT NULL DEFAULT 240 CHECK (box_width BETWEEN 160 AND 480),
  box_height integer NOT NULL DEFAULT 96 CHECK (box_height BETWEEN 64 AND 240),
  updated_at timestamptz NOT NULL DEFAULT now()
);
