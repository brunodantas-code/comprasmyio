CREATE TABLE public.mytosis_nodes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  locator integer GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  kind text NOT NULL DEFAULT 'task' CHECK (kind IN ('objective','task')),
  title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
  description text,
  parent_id uuid REFERENCES public.mytosis_nodes(id) ON DELETE CASCADE,
  responsible_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  due_date date,
  weight numeric NOT NULL DEFAULT 0 CHECK (weight >= 0 AND weight <= 100),
  progress numeric NOT NULL DEFAULT 0 CHECK (progress >= 0 AND progress <= 100),
  position integer NOT NULL DEFAULT 0,
  created_by uuid DEFAULT auth.uid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX mytosis_nodes_parent_idx ON public.mytosis_nodes(parent_id);

CREATE TABLE public.mytosis_links (
  predecessor_id uuid NOT NULL REFERENCES public.mytosis_nodes(id) ON DELETE CASCADE,
  successor_id uuid NOT NULL REFERENCES public.mytosis_nodes(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (predecessor_id, successor_id),
  CHECK (predecessor_id <> successor_id)
);

CREATE OR REPLACE FUNCTION public.mytosis_users()
RETURNS TABLE(id uuid, full_name text, email text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT p.id, coalesce(nullif(p.full_name,''), p.email, 'Usuário'), p.email
  FROM public.profiles p
  WHERE p.deleted_at IS NULL AND public.mytosis_role(auth.uid()) IS NOT NULL
  ORDER BY 2
$$;

