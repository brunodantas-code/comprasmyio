CREATE TRIGGER site_survey_questions_updated_at BEFORE UPDATE ON public.site_survey_questions FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
CREATE TRIGGER site_survey_visits_updated_at BEFORE UPDATE ON public.site_survey_visits FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
