CREATE OR REPLACE FUNCTION public.has_site_survey_permission(_user_id uuid, _permission text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.user_app_access uaa
    JOIN public.user_access_profiles uap ON uap.user_id = uaa.user_id
    LEFT JOIN public.access_profile_definitions apd ON apd.code = uap.profile_definition_id
    WHERE uaa.user_id = _user_id
      AND uaa.app_key = 'site_survey'
      AND (
        apd.base_profile = 'admin'
        OR (
          uap.is_customized = true
          AND EXISTS (
            SELECT 1 FROM public.user_menu_permissions ump
            WHERE ump.user_id = _user_id AND ump.menu_key = _permission AND ump.allowed = true
          )
        )
        OR (
          uap.is_customized = false
          AND EXISTS (
            SELECT 1 FROM public.access_profile_permissions app
            WHERE app.profile_code = uap.profile_definition_id AND app.menu_key = _permission AND app.allowed = true
          )
        )
      )
  )
$$;
REVOKE ALL ON FUNCTION public.has_site_survey_permission(uuid, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.has_site_survey_permission(uuid, text) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.can_view_site_survey_visit(_visit_id uuid, _user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.site_survey_visits v
    WHERE v.id = _visit_id
      AND (
        public.has_site_survey_permission(_user_id, 'site_survey_visitas_todas')
        OR (
          public.has_site_survey_permission(_user_id, 'site_survey_visitas_minhas')
          AND (v.technician_id = _user_id OR v.created_by = _user_id)
        )
      )
  )
$$;
REVOKE ALL ON FUNCTION public.can_view_site_survey_visit(uuid, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.can_view_site_survey_visit(uuid, uuid) TO authenticated, service_role;

