CREATE OR REPLACE FUNCTION public.get_site_survey_users()
RETURNS TABLE(id uuid, full_name text, email text)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p.id, p.full_name, p.email
  FROM public.profiles p
  JOIN public.user_app_access uaa ON uaa.user_id = p.id AND uaa.app_key = 'site_survey'
  WHERE p.deleted_at IS NULL
    AND (
      public.has_site_survey_permission(auth.uid(), 'site_survey_agendar')
      OR public.has_site_survey_permission(auth.uid(), 'site_survey_editar')
      OR public.has_site_survey_permission(auth.uid(), 'site_survey_perfis')
    )
  ORDER BY p.full_name
$$;
REVOKE ALL ON FUNCTION public.get_site_survey_users() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_site_survey_users() TO authenticated, service_role;

