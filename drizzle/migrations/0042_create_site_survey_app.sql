CREATE OR REPLACE FUNCTION public.log_site_survey_visit_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.site_survey_logs (visit_id, actor_id, action, details)
    VALUES (NEW.id, auth.uid(), 'visita_criada', jsonb_build_object('status', NEW.status));
  ELSIF NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.site_survey_logs (visit_id, actor_id, action, details)
    VALUES (NEW.id, auth.uid(), 'status_alterado', jsonb_build_object('de', OLD.status, 'para', NEW.status));
  END IF;
  RETURN NEW;
END
$$;
CREATE TRIGGER site_survey_visits_log AFTER INSERT OR UPDATE ON public.site_survey_visits FOR EACH ROW EXECUTE FUNCTION public.log_site_survey_visit_change();
